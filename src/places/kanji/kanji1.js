export const KANJI = RAW.map(([k, s]) => {
  const m = s.match(/\{(.+?)\}/);
  return { k, s, yomi: m[1], before: s.slice(0, m.index), after: s.slice(m.index + m[0].length) };
});

export const GROUP_SIZE = 10;
export const GROUPS = Array.from({ length: Math.ceil(KANJI.length / GROUP_SIZE) }, (_, i) =>
  KANJI.slice(i * GROUP_SIZE, (i + 1) * GROUP_SIZE).map((x) => x.k)
);
export const byKanji = Object.fromEntries(KANJI.map((x) => [x.k, x]));
